    PasswordRequirement("signIn.passwordChange.requirement"),
    PasswordTooShort("signIn.passwordChange.error.tooShort"),

    // DX5b
    WatchPartyVotingEyebrow("watchParty.eyebrow.voting"),
    WatchPartyHere("watchParty.connection.here"),
}
